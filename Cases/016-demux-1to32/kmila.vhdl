library ieee;
use ieee.std_logic_1164.all;

-- Independent implementation. Whole-vector case branches build the
-- 32-bit one-hot output from x in a single signal assignment, avoiding
-- the variable+per-bit-write pattern (which surfaced a 1-tick latency
-- on the y signal in initial attempts).
entity Demux1x32 is
    port (
        x   : in  std_logic;
        sel : in  std_logic_vector(4 downto 0);
        y   : out std_logic_vector(31 downto 0)
    );
end Demux1x32;

architecture rtl of Demux1x32 is
begin
    process(x, sel)
    begin
        case sel is
            when "00000" => y <= "0000000000000000000000000000000" & x;
            when "00001" => y <= "000000000000000000000000000000" & x & "0";
            when "00010" => y <= "00000000000000000000000000000" & x & "00";
            when "00011" => y <= "0000000000000000000000000000" & x & "000";
            when "00100" => y <= "000000000000000000000000000" & x & "0000";
            when "00101" => y <= "00000000000000000000000000" & x & "00000";
            when "00110" => y <= "0000000000000000000000000" & x & "000000";
            when "00111" => y <= "000000000000000000000000" & x & "0000000";
            when "01000" => y <= "00000000000000000000000" & x & "00000000";
            when "01001" => y <= "0000000000000000000000" & x & "000000000";
            when "01010" => y <= "000000000000000000000" & x & "0000000000";
            when "01011" => y <= "00000000000000000000" & x & "00000000000";
            when "01100" => y <= "0000000000000000000" & x & "000000000000";
            when "01101" => y <= "000000000000000000" & x & "0000000000000";
            when "01110" => y <= "00000000000000000" & x & "00000000000000";
            when "01111" => y <= "0000000000000000" & x & "000000000000000";
            when "10000" => y <= "000000000000000" & x & "0000000000000000";
            when "10001" => y <= "00000000000000" & x & "00000000000000000";
            when "10010" => y <= "0000000000000" & x & "000000000000000000";
            when "10011" => y <= "000000000000" & x & "0000000000000000000";
            when "10100" => y <= "00000000000" & x & "00000000000000000000";
            when "10101" => y <= "0000000000" & x & "000000000000000000000";
            when "10110" => y <= "000000000" & x & "0000000000000000000000";
            when "10111" => y <= "00000000" & x & "00000000000000000000000";
            when "11000" => y <= "0000000" & x & "000000000000000000000000";
            when "11001" => y <= "000000" & x & "0000000000000000000000000";
            when "11010" => y <= "00000" & x & "00000000000000000000000000";
            when "11011" => y <= "0000" & x & "000000000000000000000000000";
            when "11100" => y <= "000" & x & "0000000000000000000000000000";
            when "11101" => y <= "00" & x & "00000000000000000000000000000";
            when "11110" => y <= "0" & x & "000000000000000000000000000000";
            when "11111" => y <= x & "0000000000000000000000000000000";
            when others  => y <= (others => '0');
        end case;
    end process;
end rtl;
