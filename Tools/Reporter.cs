using System.Text;
using System.Text.Json;
using Kmila.Shared.Services.Vcd;

namespace SimulatorBench.Tools;

public static class Reporter
{
    /// <summary>Indented JSON for every file the bench writes (report, diffs, audits).</summary>
    public static readonly JsonSerializerOptions Indented = new() { WriteIndented = true };

    public sealed class CaseResult
    {
        public string Id { get; set; } = "";
        public string Title { get; set; } = "";
        public bool Pass { get; set; }
        public bool Skipped { get; set; }
        public string? SkipReason { get; set; }
        /// <summary>Catalogued engine gap behind this case's mismatch (meta <c>knownGap</c>), or null.</summary>
        public string? KnownGap { get; set; }
        /// <summary>Per-port comparison against the golden dump (null when a simulator failed first).</summary>
        public List<SignalDiff>? Diff { get; set; }
        public string? GhdlError { get; set; }
        public string? KmilaError { get; set; }
        public long KmilaMs { get; set; }
        // 2026-07-20 Phase 21 — populated only when `run --roundtrip` was
        // active; zero otherwise. Reported alongside the [PASS]/[FAIL]
        // flag so triage can see which cases carried raw-fallback residue
        // or silent-loss diagnostics through the round-trip.
        public int RoundTripRaws { get; set; }
        public int RoundTripDiags { get; set; }
    }

    public static void WriteConsoleSummary(IReadOnlyList<CaseResult> results)
    {
        int total = results.Count;
        int skipped = results.Count(r => r.Skipped);
        int evalable = total - skipped;
        int passed = results.Count(r => r.Pass);
        int gaps = results.Count(r => !r.Pass && r.KnownGap != null);
        double accuracy = evalable > 0 ? 100.0 * passed / evalable : 0;

        Console.WriteLine();
        Console.WriteLine(new string('=', 64));
        Console.WriteLine($" SimulatorBench summary");
        Console.WriteLine(new string('=', 64));
        // Phase 21: any case carrying RT metrics implies --roundtrip was
        // active. Show them inline on the PASS/FAIL line for at-a-glance
        // triage.
        bool anyRt = results.Any(r => r.RoundTripRaws > 0 || r.RoundTripDiags > 0);
        foreach (var r in results)
        {
            string flag = r.Skipped ? "SKIP" : r.Pass ? "PASS" : r.KnownGap != null ? "GAP" : "FAIL";
            string rt = anyRt
                ? $"  RT: {r.RoundTripRaws} raws / {r.RoundTripDiags} diags"
                : "";
            Console.WriteLine($"  [{flag}] {r.Id,-32} {r.Title}{rt}");
            if (r.Skipped) Console.WriteLine($"         skip: {r.SkipReason}");
            if (r.KnownGap != null) Console.WriteLine($"         known gap: {r.KnownGap}");
            if (!r.Skipped && !r.Pass && r.Diff != null)
            {
                foreach (var pd in r.Diff.Where(p => !p.Equal))
                {
                    if (pd.Missing != MissingSide.None) Console.WriteLine($"         {pd.Signal}: skipped — {pd.MissingFrom("golden VCD", "kmila VCD")}");
                    else
                    {
                        Console.WriteLine($"         {pd.Signal}: {pd.Mismatches}/{pd.Samples} mismatched");
                        foreach (var ex in pd.Examples) Console.WriteLine($"           · {ExampleText(ex)}");
                    }
                }
                if (!string.IsNullOrEmpty(r.GhdlError))  Console.WriteLine($"         ghdl:  {Truncate(r.GhdlError, 200)}");
                if (!string.IsNullOrEmpty(r.KmilaError)) Console.WriteLine($"         kmila: {Truncate(r.KmilaError, 200)}");
            }
        }
        Console.WriteLine(new string('-', 64));
        Console.WriteLine($"  {passed}/{evalable} passed  ({accuracy:F1}%)   known-gaps={gaps}   skipped={skipped}   total={total}");
        Console.WriteLine();
    }

    public static void WriteJson(string path, IReadOnlyList<CaseResult> results)
    {
        File.WriteAllText(path, JsonSerializer.Serialize(results, Indented));
    }

    // Markdown accuracy report — pass rate + timing distribution + per-prefix
    // buckets (numeric id categories like `000-`, `100-`) + a round-trip
    // watch-list for cases that carried raws/diags even while passing.
    // Regenerated by the `report` subcommand from an existing report.json.
    public static void WriteMarkdownAccuracy(string outPath, IReadOnlyList<CaseResult> results, string sourceJsonPath)
    {
        int total = results.Count;
        int skipped = results.Count(r => r.Skipped);
        int passed  = results.Count(r => r.Pass && !r.Skipped);
        int failed  = results.Count(r => !r.Pass && !r.Skipped);
        int evalable = total - skipped;
        double acc = evalable > 0 ? 100.0 * passed / evalable : 0;

        var timings = results.Where(r => !r.Skipped).Select(r => r.KmilaMs).OrderBy(x => x).ToList();
        long p50 = timings.Count > 0 ? timings[timings.Count / 2] : 0;
        long p95 = timings.Count > 0 ? timings[Math.Min(timings.Count - 1, (int)(timings.Count * 0.95))] : 0;
        long sumMs = timings.Sum();
        long maxMs = timings.Count > 0 ? timings[^1] : 0;

        var buckets = results.GroupBy(r => BucketOf(r.Id))
            .OrderBy(g => g.Key)
            .Select(g => new {
                Prefix = g.Key,
                Total = g.Count(),
                Pass = g.Count(r => r.Pass && !r.Skipped),
                Fail = g.Count(r => !r.Pass && !r.Skipped),
                Skip = g.Count(r => r.Skipped)
            }).ToList();

        var rtWatch = results.Where(r => r.RoundTripRaws > 0 || r.RoundTripDiags > 0)
                             .OrderByDescending(r => r.RoundTripRaws + r.RoundTripDiags).ToList();

        var failures = results.Where(r => !r.Pass && !r.Skipped).ToList();

        var sb = new StringBuilder();
        sb.AppendLine("# SimulatorBench — Accuracy Report");
        sb.AppendLine();
        sb.AppendLine($"Generated from `{Path.GetFileName(sourceJsonPath)}` — regenerate with `dotnet run --project SimulatorBench -- report`.");
        sb.AppendLine();
        sb.AppendLine("## Summary");
        sb.AppendLine();
        sb.AppendLine("| Metric | Value |");
        sb.AppendLine("|---|---|");
        sb.AppendLine($"| Cases evaluated | {evalable} |");
        sb.AppendLine($"| Passed          | {passed} ({acc:F1}%) |");
        sb.AppendLine($"| Failed          | {failed} |");
        sb.AppendLine($"| Skipped         | {skipped} |");
        sb.AppendLine($"| Total wall-time | {sumMs} ms |");
        sb.AppendLine($"| Per-case p50 / p95 / max | {p50} / {p95} / {maxMs} ms |");
        sb.AppendLine($"| Round-trip watch-list | {rtWatch.Count} case(s) with residual raws or diagnostics |");
        sb.AppendLine();

        sb.AppendLine("## Category breakdown");
        sb.AppendLine();
        sb.AppendLine("Cases are grouped by their numeric id prefix (e.g. `000-smoke-*`, `146-procedure-*`).");
        sb.AppendLine();
        sb.AppendLine("| Prefix | Pass | Fail | Skip | Total |");
        sb.AppendLine("|---|---:|---:|---:|---:|");
        foreach (var b in buckets)
            sb.AppendLine($"| `{b.Prefix}` | {b.Pass} | {b.Fail} | {b.Skip} | {b.Total} |");
        sb.AppendLine();

        if (failures.Count > 0)
        {
            sb.AppendLine("## Failures");
            sb.AppendLine();
            foreach (var f in failures)
            {
                sb.AppendLine($"### `{f.Id}` — {f.Title}");
                if (!string.IsNullOrEmpty(f.GhdlError))
                    sb.AppendLine($"- **GHDL error**: `{Truncate(f.GhdlError, 200)}`");
                if (!string.IsNullOrEmpty(f.KmilaError))
                    sb.AppendLine($"- **Kmila error**: `{Truncate(f.KmilaError, 200)}`");
                if (f.Diff != null)
                    foreach (var pd in f.Diff.Where(p => !p.Equal))
                    {
                        if (pd.Missing != MissingSide.None)
                            sb.AppendLine($"- port `{pd.Signal}` skipped — {pd.MissingFrom("golden VCD", "kmila VCD")}");
                        else
                            sb.AppendLine($"- port `{pd.Signal}` — {pd.Mismatches}/{pd.Samples} mismatched");
                    }
                sb.AppendLine();
            }
        }

        if (rtWatch.Count > 0)
        {
            sb.AppendLine("## Round-trip watch-list");
            sb.AppendLine();
            sb.AppendLine("Cases that carried raw-fallback residue or silent-loss diagnostics through the `--roundtrip` pass even though they still passed the diff. Non-blocking; useful for triage.");
            sb.AppendLine();
            sb.AppendLine("| Case | Raws | Diags |");
            sb.AppendLine("|---|---:|---:|");
            foreach (var r in rtWatch)
                sb.AppendLine($"| `{r.Id}` | {r.RoundTripRaws} | {r.RoundTripDiags} |");
            sb.AppendLine();
        }

        File.WriteAllText(outPath, sb.ToString());
    }

    private static string BucketOf(string id)
    {
        // Group by hundreds of the numeric id prefix (e.g. "005-…" → "000-099",
        // "146-…" → "100-199"). Keeps the category table short as the corpus
        // grows past a few dozen cases.
        var dash = id.IndexOf('-');
        if (dash < 0 || !int.TryParse(id.AsSpan(0, dash), out int n)) return id;
        int lo = (n / 100) * 100;
        return $"{lo:D3}-{lo + 99:D3}";
    }

    private static string Truncate(string s, int n) => s.Length <= n ? s : s.Substring(0, n) + "…";

    /// <summary>One mismatch as the bench has always printed it.</summary>
    public static string ExampleText(ValueMismatch m) => $"t={m.TimeFs}fs  golden={m.Expected}  kmila={m.Actual}";
}
